SELECT 
    C.CITY,
    C.CUSTOMER_ID,
    SUM(P.PRICE) AS TOTAL_PRICE
FROM CUSTOMERS C
INNER JOIN ORDERS O 
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN PRODUCTS P 
    ON P.PRODUCT_ID = O.PRODUCT_ID
WHERE C.CITY IN ('NAGPUR','PUNE','MUMBAI','NASHIK')
GROUP BY C.CITY, C.CUSTOMER_ID ORDER BY SUM(P.PRICE) DESC;

