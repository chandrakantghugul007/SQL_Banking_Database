SELECT 
    P.CATEGORY,DAYNAME(O.ORDER_DATE)AS ORDER_DATE,
    SUM(P.PRICE) AS TOTAL_PRICE,
    C.CITY
FROM CUSTOMERS C
INNER JOIN ORDERS O 
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN PRODUCTS P 
    ON P.PRODUCT_ID = O.PRODUCT_ID
GROUP BY 
 DAYNAME(O.ORDER_DATE),CITY,P.CATEGORY
ORDER BY 
SUM(P.PRICE) DESC;


SELECT 
    C.CUSTOMER_ID,COUNT(O.ORDER_ID) AS NUMBER_OF_ORDERS
FROM CUSTOMERS C
INNER JOIN ORDERS O 
    ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN PRODUCTS P 
    ON P.PRODUCT_ID = O.PRODUCT_ID
GROUP BY 
C.CUSTOMER_ID
HAVING COUNT(O.ORDER_ID)>1
ORDER BY 
COUNT(O.ORDER_ID) DESC;

